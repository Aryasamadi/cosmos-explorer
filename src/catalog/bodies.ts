export const CORE_BODY_IDS = ['earth', 'moon', 'sun', 'mars'] as const;

export function getBodyById(id: string): CelestialBody | undefined {
  return BODY_CATALOG.find((body) => body.id === id);
}

export function getSkyBodies(): readonly CelestialBody[] {
  return BODY_CATALOG.filter((body) => body.skyVisible);
}

export function getFreeExploreBodies(): readonly CelestialBody[] {
  return BODY_CATALOG.filter((body) => CORE_BODY_IDS.includes(body.id as (typeof CORE_BODY_IDS)[number]));
}
